"""Model card for the deployed bundle: models/MODEL_CARD.md, rendered from models/manifest.json,
results/p4/selection.json and results/p4/eval.json only (no number typed by hand).

The Phase 2 card (single CNN + crop head, still used by the website's showcase) is
models/MODEL_CARD_phase2.md, written by scripts/train_robust.py.

    python scripts/model_card.py            # write models/MODEL_CARD.md
    python scripts/model_card.py --check    # exit 1 if it differs from a fresh render
"""

from __future__ import annotations

import json
import sys

from leafdx.config import ROOT, load_config, path


def f3(x) -> str:
    return "n/a" if x is None else f"{x:.3f}"


def pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.0f}%"


def ci(m: dict) -> str:
    lo, hi = m["ci95"]["macro_f1"]
    return f"{m['macro_f1']:.3f} [{lo:.3f}, {hi:.3f}]"


SET_NAMES = {"p4_test": "p4_test: held-out field leaves", "wild_ext": "wild_ext: extended field set",
             "wild": "wild: first field set", "test": "clean TEST"}


def render(M: dict, SEL: dict, EV: dict) -> str:
    prod, tr, cal = M["production"], M["trust"], SEL["calibration"]
    arm = M["arms"][prod["disease"]]
    cand = SEL["candidates"][prod["disease_config"]]
    n = SEL["n"]
    L = ["# Model card: deployed bundle", "",
         "Generated by `scripts/model_card.py` from models/manifest.json, results/p4/selection.json and "
         "results/p4/eval.json. Do not edit by hand. The Phase 2 card (single CNN, still used for the website's "
         "worked example) is [MODEL_CARD_phase2.md](MODEL_CARD_phase2.md).", "",
         "## What it does", "",
         "Takes one leaf photo and answers: which crop (turmeric or black gram), healthy or diseased, how much of the "
         "leaf is affected, and how sure it is. When a check fails it declines to answer instead of guessing "
         "(not a leaf of either crop, blurred or dark photo, or more than one label plausible).", "",
         f"Bundle `models/manifest.json`, created {M['created']}. Reason: {prod['reason']}.", "",
         "## Components", "",
         "| role | configuration | file | trained on |", "|---|---|---|---|",
         f"| crop ID | `{M['crop']['config']}` (C {cal['crop_C']}) | `{M['crop']['file']}` | "
         "clean TRAIN + swap views + p4_train targets |",
         f"| disease (production) | `{prod['disease_config']}`, head {', '.join(cand['heads'].values())} | `{arm['file']}` | "
         f"{arm.get('trained_on', 'clean TRAIN (Phase 3)')} |",
         f"| OOD gate | kNN (k {tr['ood_k']}) on `{tr['ood_backbone']}` embeddings, threshold {tr['ood_threshold']:.3f} | "
         f"`{tr['ood_reference']}` | {cal['ood_reference_rows']} reference leaves |",
         f"| conformal sets | LAC, alpha {tr['alpha']}: disease q {tr['disease_q_lac']:.3f}, crop q {tr['crop_q_lac']:.3f} | "
         f"models/manifest.json | calibrated on {tr['calibrated_on']} |",
         f"| quality gate | blur >= {tr['quality']['blur_min']}, dark / bright share <= {tr['quality']['dark_max']} / "
         f"{tr['quality']['bright_max']}, leaf share >= {tr['quality']['min_leaf_frac']} | configs/default.yaml | rules |",
         "", f"Disease temperature {cal['temperature']:.2f}. CPU time of the disease model: {cand['ms']:.0f} ms per image "
         "(results/p3/timing.json).", "",
         "The other disease models ship for the side-by-side view on /analyze; they do not change the answer:", ""]
    L += [f"- `{v['config']}` (`{v['file']}`)" for k, v in M["arms"].items() if k != prod["disease"]]
    L += ["", "## Training data", "",
          "- Clean TRAIN split of the two lab datasets (turmeric Mendeley g46dvrcvwn, black gram BPLD zfcv9fmrgv) "
          "plus background-swap views.",
          f"- p4_train: {n['p4_train']} disease-labelled field leaves ("
          + ", ".join(f"{k} {v}" for k, v in n["p4_train_by_crop_label"].items()) + "), grouped by capture minute, "
          "field scene and near-duplicate so no group crosses p4_train / p4_val / p4_test (data/p4, docs/PLAN_phase4_more_data.md).",
          "- Sources and licences: docs/LICENSES.md (all data CC BY 4.0).", "",
          "## Selection", "",
          f"{len(SEL['candidates'])} configurations re-fitted and scored on p4_val ({n['p4_val']} leaves). Best point "
          f"`{SEL['selection']['best_point']}` ({f3(SEL['selection']['best_f1'])}); {len(SEL['selection']['tied'])} "
          f"configurations (it included) scored within its CI, and the pre-registered rule took the fastest of them: "
          f"`{SEL['selection']['winner']}` "
          f"({f3(SEL['selection']['winner_f1'])}).", "",
          "## Results (scored once, previous bundle -> this bundle)", "",
          f"Previous production `{EV['old']['disease_config']}`. Macro-F1 with 95% grouped-bootstrap CI; disease scored "
          "with the true crop.", "",
          "| set | n | previous | this bundle | paired diff [CI] |", "|---|---|---|---|---|"]
    for s, name in SET_NAMES.items():
        r = EV["sets"][s]
        d = r["new_minus_old_macro_f1"]
        L.append(f"| {name} | {r['n']} | {ci(r['old']['pooled'])} | {ci(r['new']['pooled'])} | "
                 f"{d['diff']:+.3f} [{d['ci95'][0]:+.3f}, {d['ci95'][1]:+.3f}] |")
    L += [""]
    for s in ("p4_test", "wild_ext"):
        r = EV["sets"][s]
        L.append(f"- {s} per crop: " + "; ".join(
            f"{c} {f3(r['old'][c]['macro_f1'])} -> {f3(r['new'][c]['macro_f1'])} (n {r['new'][c]['n']})"
            for c in ("turmeric", "blackgram") if c in r["new"] and c in r["old"]))
    g = EV["trust_p4_test"]
    L += [f"- With the gates on (p4_test, quality gate not re-run): answers {pct(g['new']['answered_share_labelled'])} of "
          f"labelled leaves (previous {pct(g['old']['answered_share_labelled'])}), right on "
          f"{f3(g['new']['end_to_end_accuracy_answered'])} of those; crop ID {f3(g['new']['crop_accuracy_all_targets'])} "
          f"on {g['new']['n_targets']} leaves; declines {pct(g['new']['other_species_refused'])} of "
          f"{g['new']['n_other']} other-species leaves.", "",
          "Full numbers: results/p4_report.md. Previous bundles: models/manifest_field.json (Phase 3, field-validated), "
          "models/manifest_phase3.json (Phase 3, lab-validated).", "",
          "## Intended use and limits", "",
          "- Research prototype for turmeric and black gram leaves; not a substitute for an agronomist.",
          "- Field data come from a handful of Mendeley datasets (docs/LICENSES.md); wild / wild_ext share sources (not photos, scenes "
          "or capture minutes) with p4_train, so they measure new photos from known sources. Results on unseen sources: "
          "results/final_report.md (Phase 3).",
          f"- Turmeric field leaves with disease labels are few (p4_test n {EV['sets']['p4_test']['new']['turmeric']['n']}); "
          "turmeric field numbers carry wide intervals.",
          "- Labels are the dataset authors'; no agronomist re-check.", ""]
    return "\n".join(L)


def main() -> int:
    cfg = load_config()
    res = path("results", cfg)
    M = json.loads((ROOT / "models/manifest.json").read_text())
    SEL = json.loads((res / "p4" / "selection.json").read_text())
    EV = json.loads((res / "p4" / "eval.json").read_text())
    text = render(M, SEL, EV)
    out = path("models", cfg) / "MODEL_CARD.md"
    if "--check" in sys.argv:
        ok = out.exists() and out.read_text() == text
        print("MODEL_CARD.md matches a fresh render" if ok else "MISMATCH with a fresh render")
        return 0 if ok else 1
    out.write_text(text)
    print(f"wrote {out.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
