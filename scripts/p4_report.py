"""Phase 4 report: results/p4_report.md, rendered from data/p4/summary.json, results/p4/selection.json and
results/p4/eval.json only (no number is typed by hand).

    python scripts/p4_report.py            # write results/p4_report.md
    python scripts/p4_report.py --check    # exit 1 if it differs from a fresh render
"""

from __future__ import annotations

import json
import sys

from leafdx.config import ROOT, load_config, path


def f3(x) -> str:
    return "n/a" if x is None else f"{x:.3f}"


def ci(m: dict, k: str = "macro_f1") -> str:
    lo, hi = m["ci95"][k]
    return f"{m[k]:.3f} [{lo:.3f}, {hi:.3f}]"


def pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.0f}%"


def render(S: dict, SEL: dict, EV: dict | None) -> str:
    L = ["# Phase 4 report: training with more field data", "",
         "Generated by `scripts/p4_report.py` from data/p4/summary.json, results/p4/selection.json and "
         "results/p4/eval.json. Do not edit by hand. Plan (pre-registered): docs/PLAN_phase4_more_data.md.", "",
         "## Data pool", "",
         f"- {S['n']} images in {S['n_groups']} groups (capture minute, field scene, leaf pair, strong pHash duplicate); "
         f"{S['dropped_near_duplicates_of_existing']} near-duplicates of clean / wild / wild_ext images dropped; "
         f"{S['excluded']['field_val_rows_sharing_a_test_capture_minute']} field_val images dropped because a test image "
         "was taken in the same minute (Phase 3's minute rule missed IMGyyyymmddhhmmss names).",
         "- By source: " + ", ".join(f"{k} {v}" for k, v in S["by_source"].items()) + ".", "",
         "| split | " + " | ".join(sorted({k for v in S["by_split"].values() for k in v})) + " |",
         "|---" * (1 + len({k for v in S["by_split"].values() for k in v})) + "|"]
    cols = sorted({k for v in S["by_split"].values() for k in v})
    for s in ("p4_train", "p4_val", "p4_test"):
        L.append(f"| {s} | " + " | ".join(str(S["by_split"].get(s, {}).get(c, 0)) for c in cols) + " |")
    L += ["", "`unknown` = crop label only (PhilMedic turmeric) or other species: these train / test crop ID and the "
          "OOD gate, never a disease head.", "",
          "## Selection on p4_val", "",
          f"Every configuration re-fitted on clean TRAIN (+ swap views) + p4_train ({SEL['n']['p4_train']} disease-labelled "
          f"field leaves); scored on p4_val ({SEL['n']['p4_val']} leaves, {SEL['n']['p4_val_groups']} groups).", "",
          "| configuration | p4_val macro-F1 | turmeric | black gram | clean VAL macro-F1 | CPU ms/img |", "|---|---|---|---|---|---|"]
    for c, v in sorted(SEL["candidates"].items(), key=lambda kv: -kv[1]["p4_val_macro_f1"])[:12]:
        mark = " (chosen)" if c == SEL["selection"]["winner"] else ""
        L.append(f"| `{c}`{mark} | {f3(v['p4_val_macro_f1'])} | {f3(v['turmeric_p4_val_f1'])} | "
                 f"{f3(v['blackgram_p4_val_f1'])} | {f3(v['val_macro_f1'])} | {v['ms']:.0f} |")
    sel, cal = SEL["selection"], SEL["calibration"]
    L += ["", f"Best point estimate `{sel['best_point']}` ({f3(sel['best_f1'])}, lower CI bound {f3(sel['best_ci_low'])}); "
          f"by the tie rule the fastest tied candidate was chosen: **`{sel['winner']}`** ({f3(sel['winner_f1'])}).",
          f"Calibration on p4_val: temperature {cal['temperature']:.2f}; crop head C={cal['crop_C']}, p4_val crop accuracy "
          f"{f3(cal['crop_accuracy_p4_val'])}; kNN OOD threshold {cal['ood_threshold']:.3f} over {cal['ood_reference_rows']} "
          f"reference leaves (refuses {pct(cal['ood_other_species_refused_p4_val'])} of p4_val other-species leaves on its own).", ""]
    if not EV:
        return "\n".join(L + ["Evaluation not run yet (scripts/p4_eval.py).", ""])
    L += ["## Once-only evaluation: Phase 4 vs previous production", "",
          f"Previous production `{EV['old']['disease_config']}`; Phase 4 `{EV['new']['disease_config']}`. Disease scored with "
          "the true crop. 95% grouped-bootstrap CIs.", "",
          "| set | n | previous macro-F1 | Phase 4 macro-F1 | paired diff [CI] | McNemar (new right / old right, p) |",
          "|---|---|---|---|---|---|"]
    names = {"test": "clean TEST", "p4_test": "p4_test (held-out field)", "wild": "wild", "wild_ext": "wild_ext"}
    for s in ("test", "p4_test", "wild", "wild_ext"):
        r = EV["sets"][s]
        d, mc = r["new_minus_old_macro_f1"], r["mcnemar_new_vs_old"]
        L.append(f"| {names[s]} | {r['n']} | {ci(r['old']['pooled'])} | {ci(r['new']['pooled'])} | "
                 f"{d['diff']:+.3f} [{d['ci95'][0]:+.3f}, {d['ci95'][1]:+.3f}] | "
                 f"{mc['a_right_b_wrong']} / {mc['a_wrong_b_right']}, p {mc['p_value']:.2g} |")
    L += ["", "Per crop (macro-F1, previous -> Phase 4):", ""]
    for s in ("p4_test", "wild_ext", "test"):
        r = EV["sets"][s]
        parts = [f"{c} {f3(r['old'][c]['macro_f1'])} -> {f3(r['new'][c]['macro_f1'])} (n {r['new'][c]['n']})"
                 for c in ("turmeric", "blackgram") if c in r["new"] and c in r["old"]]
        L.append(f"- {names[s]}: " + "; ".join(parts))
    g = EV["trust_p4_test"]
    L += ["", "Trust gates on p4_test (OOD + conformal crop + conformal disease; quality gate not re-run):", "",
          "| | previous | Phase 4 |", "|---|---|---|",
          f"| crop ID accuracy, all target leaves (n {g['new']['n_targets']}) | {f3(g['old']['crop_accuracy_all_targets'])} | "
          f"{f3(g['new']['crop_accuracy_all_targets'])} |",
          f"| answered share (labelled leaves) | {pct(g['old']['answered_share_labelled'])} | {pct(g['new']['answered_share_labelled'])} |",
          f"| end-to-end accuracy on answered | {f3(g['old']['end_to_end_accuracy_answered'])} | {f3(g['new']['end_to_end_accuracy_answered'])} |",
          f"| end-to-end accuracy, all labelled leaves | {f3(g['old']['end_to_end_accuracy_all'])} | {f3(g['new']['end_to_end_accuracy_all'])} |",
          f"| other species refused (n {g['new']['n_other']}) | {pct(g['old']['other_species_refused'])} | {pct(g['new']['other_species_refused'])} |",
          ""]
    sw = EV["switch"]
    L += [f"Switch rule (pre-registered): p4_test paired CI lower bound {sw['p4_test_ci_low']:+.3f} "
          f"({'> 0' if sw['p4_test_better'] else '<= 0'}); clean TEST {f3(sw['clean_test_old'])} -> {f3(sw['clean_test_new'])} "
          f"({'within' if sw['clean_test_within_0.02'] else 'outside'} 0.02). "
          f"**Production switched: {'yes' if sw['switched'] else 'no'}.**", "",
          "## Limits", "",
          "- Phase 4 trains on other images from the same Bangladeshi sources as wild / wild_ext, so those two sets now "
          "measure new images from known sources, not new sources; the Phase 3 numbers in final_report.md keep that claim.",
          "- Turmeric field training data are small; turmeric changes carry wide intervals.",
          "- Labels are the dataset authors'; no agronomist re-check.", ""]
    return "\n".join(L)


def main() -> int:
    cfg = load_config()
    res = path("results", cfg)
    S = json.loads((ROOT / cfg["p4"]["root"] / "summary.json").read_text())
    SEL = json.loads((res / "p4" / "selection.json").read_text())
    ev = res / "p4" / "eval.json"
    text = render(S, SEL, json.loads(ev.read_text()) if ev.exists() else None)
    out = res / "p4_report.md"
    if "--check" in sys.argv:
        ok = out.exists() and out.read_text() == text
        print("p4_report.md matches a fresh render" if ok else "MISMATCH with a fresh render")
        return 0 if ok else 1
    out.write_text(text)
    print(f"wrote {out.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
