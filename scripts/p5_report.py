"""Phase 5 report: results/p5_report.md, rendered from results/p5/selection.json and results/p5/eval.json only
(no number is typed by hand). `--check` compares the file with a fresh render (used by scripts/verify_all.py).
"""

from __future__ import annotations

import json
import sys

from leafdx.config import load_config, path


def f3(x) -> str:
    return "n/a" if x is None else f"{x:.3f}"


def pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def ci(m: dict) -> str:
    lo, hi = m["ci95"]["macro_f1"]
    return f"{m['macro_f1']:.3f} [{lo:.3f}, {hi:.3f}]"


SET_NAMES = {"p4_test": "p4_test: held-out field leaves (second read)", "wild_ext": "wild_ext: extended field set",
             "wild": "wild: first field set", "test": "clean TEST"}
RULES = {"f1_no_loss": "p4_test macro-F1 difference: point >= -0.005 and CI lower bound > -0.02",
         "answers_more": "share of p4_test leaves answered is higher",
         "accuracy_answered_ok": "end-to-end accuracy on answered p4_test leaves >= 0.97",
         "clean_test_within_0.02": "clean TEST macro-F1 drops by no more than 0.02",
         "other_species_ok": "other-species refusal not lower by more than one leaf"}


def render(SEL: dict, EV: dict) -> str:
    c, s, t = SEL["candidates"], SEL["selection"], SEL["thresholds"]
    L = ["# Phase 5: sharper answers, fewer needless refusals", "",
         "Generated by `scripts/p5_report.py` from results/p5/selection.json and results/p5/eval.json. Do not edit by "
         "hand. Plan (pre-registered): docs/PLAN_phase5_confidence.md.", "",
         "Nothing was trained in this phase. Every disease head is a Phase 4 fit; Phase 5 chooses how to combine them and "
         "where to put the refusal thresholds, on validation data only.", "",
         "## Selection on p4_val", "",
         f"p4_val {SEL['n']['p4_val']} disease-labelled leaves, clean VAL {SEL['n']['val']}. NLL = mean negative "
         "log-likelihood after temperature scaling; \"conf. right\" = mean confidence on correct answers.", "",
         "| candidate | members | p4_val macro-F1 | p4_val NLL | p4_val ECE | conf. right | clean VAL macro-F1 | admissible |",
         "|---|---|---|---|---|---|---|---|"]
    for k, v in c.items():
        L.append(f"| {k} | {' + '.join(v['members'])} | {f3(v['p4_val']['macro_f1'])} | {v['p4_val']['nll']:.4f} | "
                 f"{f3(v['p4_val']['ece'])} | {f3(v['p4_val']['mean_confidence_right'])} | {f3(v['val']['macro_f1'])} | "
                 f"{'yes' if v['admissible'] else 'no'} |")
    L += ["", f"Lowest NLL {s['best_nll']:.4f}; tied within 0.005 nats: {', '.join(s['tied'])}; fewest members wins: "
          f"**{s['winner']}**.", "",
          "## Refusal thresholds (p4_val)", "",
          "| gate | before | after | answered after | wrong among answered | 95% upper bound on error |", "|---|---|---|---|---|---|",
          f"| disease confidence | {f3(t['disease']['old']['tau'])} | {f3(t['disease']['tau'])} | "
          f"{t['disease']['answered']} of {t['disease']['n']} | {t['disease']['errors']} | {pct(t['disease']['error_upper_bound'])} |",
          f"| crop confidence | {f3(t['crop']['old']['tau'])} | {f3(t['crop']['tau'])} | {t['crop']['answered']} of {t['crop']['n']} | "
          f"{t['crop']['errors']} | {pct(t['crop']['error_upper_bound'])} |", "",
          f"The crop threshold barely moves: any lower value lets through one of the {t['crop']['old']['n_other']} "
          f"other-species leaves of p4_val (refused share stays {pct(t['crop']['other_species_refused'])}), and the plan "
          "does not allow that.", "",
          f"All gates together on p4_val (quality gate not re-run): answered {pct(SEL['gates_p4_val']['old']['answered_share'])} "
          f"-> {pct(SEL['gates_p4_val']['new']['answered_share'])}; wrong among answered "
          f"{SEL['gates_p4_val']['old']['errors_answered']} -> {SEL['gates_p4_val']['new']['errors_answered']}.", "",
          "## Evaluation: Phase 4 bundle -> Phase 5 bundle", "",
          f"Protocol: {EV['protocol']}. Macro-F1 with 95% grouped-bootstrap CI; disease scored with the true crop.", "",
          "| set | n | Phase 4 | Phase 5 | paired diff [CI] | McNemar p | conf. right | ECE |", "|---|---|---|---|---|---|---|---|"]
    for k, name in SET_NAMES.items():
        r = EV["sets"][k]
        d = r["new_minus_old_macro_f1"]
        o, n = r["old"]["pooled"], r["new"]["pooled"]
        L.append(f"| {name} | {r['n']} | {ci(o)} | {ci(n)} | {d['diff']:+.3f} [{d['ci95'][0]:+.3f}, {d['ci95'][1]:+.3f}] | "
                 f"{r['mcnemar_new_vs_old']['p_value']:.3f} | {f3(o['confidence']['mean_confidence_right'])} -> "
                 f"{f3(n['confidence']['mean_confidence_right'])} | {f3(o['ece'])} -> {f3(n['ece'])} |")
    g = EV["trust_p4_test"]
    L += ["", "## Trust gates on p4_test (quality gate not re-run)", "",
          "| | Phase 4 | Phase 5 |", "|---|---|---|"]
    rows = [("answers given (labelled leaves)", lambda x: f"{x['answered_labelled']} of {x['n_labelled']} ({pct(x['answered_share_labelled'])})"),
            ("wrong among answered", lambda x: str(x["errors_answered"])),
            ("end-to-end accuracy on answered", lambda x: f3(x["end_to_end_accuracy_answered"])),
            ("end-to-end accuracy if every leaf were answered", lambda x: f3(x["end_to_end_accuracy_all"])),
            ("refused by the crop gate", lambda x: pct(x["refused_by"]["crop_gate"])),
            ("refused by the OOD gate", lambda x: pct(x["refused_by"]["ood_gate"])),
            ("refused by the disease gate", lambda x: pct(x["refused_by"]["disease_gate"])),
            ("other-species leaves refused", lambda x: f"{x['other_species_refused_n']} of {x['n_other']} ({pct(x['other_species_refused'])})"),
            ("answers when disease confidence >=", lambda x: f3(x["disease_min_confidence"])),
            ("answers when crop confidence >=", lambda x: f3(x["crop_min_confidence"]))]
    L += [f"| {name} | {fn(g['old'])} | {fn(g['new'])} |" for name, fn in rows]
    sw = EV["switch"]
    L += ["", "## Switch rule", ""]
    L += [f"- {'met' if sw[k] else 'NOT met'}: {text}" for k, text in RULES.items()]
    L += ["", f"**{'Switched' if sw['switched'] else 'Not switched'}**: models/manifest.json "
          f"{'is the Phase 5 bundle; the Phase 4 bundle stays as models/manifest_p4.json' if sw['switched'] else 'is unchanged'}.", "",
          "## What this does and does not show", "",
          "- The Phase 5 bundle answers more held-out field leaves and is at least as accurate on every set. The price, "
          "accepted in the plan before any number was seen, is that some of the extra answers are wrong: the Phase 4 "
          "bundle answered fewer leaves and got every one of those right.",
          "- p4_test was scored once before, for Phase 4's own switch. Nothing was fitted or selected on it here, but a "
          "second read is weaker evidence than a first; Phase 4's once-only numbers stay in results/p4_report.md.",
          "- The remaining refusals come mostly from the crop gate and the OOD gate, which also keep other plants out. "
          "Phase 5 did not loosen them.",
          "- Same data limits as Phase 4: field data from a few sources in one country; few disease-labelled turmeric "
          "field leaves.", ""]
    return "\n".join(L)


def main() -> int:
    cfg = load_config()
    res = path("results", cfg)
    text = render(json.loads((res / "p5" / "selection.json").read_text()), json.loads((res / "p5" / "eval.json").read_text()))
    out = res / "p5_report.md"
    if "--check" in sys.argv:
        ok = out.exists() and out.read_text() == text
        print("p5_report.md matches a fresh render" if ok else "MISMATCH with a fresh render")
        return 0 if ok else 1
    out.write_text(text)
    print(f"wrote results/p5_report.md ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
