def splice(readme_text: str, block: str) -> str:
    if BEGIN in readme_text:
        pre, rest = readme_text.split(BEGIN, 1)
        return pre + block + rest.split(END, 1)[1]
    return readme_text.rstrip() + "\n\n" + block + "\n"


def main() -> int:
    cfg = load_config()
    res = path("results", cfg)
    check = "--check" in sys.argv
    J = load(res)
    figs = figures(res, J, write=not check)
    report, block = render(J, figs)
    rf, rm = res / "final_report.md", ROOT / "README.md"
    new_readme = splice(rm.read_text(), block)
    if check:
        ok = rf.exists() and rf.read_text() == report and rm.read_text() == new_readme
        print("final_report.md / README block match a fresh render" if ok else "MISMATCH with a fresh render")
        return 0 if ok else 1
    rf.write_text(report)
    rm.write_text(new_readme)
    print(f"wrote {rf.relative_to(ROOT)} ({len(report.splitlines())} lines) and the README block")
    return 0


if __name__ == "__main__":
    sys.exit(main())
