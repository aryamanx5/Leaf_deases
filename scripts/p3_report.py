def f3(x) -> str:
    return "n/a" if x is None else f"{x:.3f}"


def ci(m: dict, k: str) -> str:
    c = (m.get("ci95") or {}).get(k)
    return f"{f3(m.get(k))} [{f3(c[0])}, {f3(c[1])}]" if c else f3(m.get(k))


def load(res):
    J = {n: json.loads((res / f"{n}.json").read_text()) for n in
         ("disease_models", "crop_models", "stacking", "trust", "robustness_p3")}
    J["audit"] = json.loads((res / "p3" / "audit.json").read_text())
    J["timing"] = json.loads((res / "p3" / "timing.json").read_text())
    J["cnn_train"] = json.loads((res / "p3_cnn_train.json").read_text())
    J["embed"] = json.loads((res / "p3" / "embed_manifest.json").read_text())
    mdir = ROOT / "models"
    # Phase 3 sections describe the Phase 3 bundle; after a field-validated switch it is kept as manifest_phase3.json
    J["manifest"] = json.loads((mdir / ("manifest_phase3.json" if (mdir / "manifest_phase3.json").exists()
                                        else "manifest.json")).read_text())
    J["manifest_current"] = json.loads((mdir / "manifest.json").read_text())
    for n in ("wild_ext", "reselection", "reselection_selection", "wild_ext_field"):
        J[n] = json.loads((res / f"{n}.json").read_text()) if (res / f"{n}.json").exists() else None
    return J


def figures(res, J, write: bool) -> list[str]:
    fig_dir = res / "figures" / "p3"
    names = ["p3_reliability.png", "p3_abstention.png", "p3_confusion.png", "p3_arms_wild.png"]
    if not write:
        return names
    fig_dir.mkdir(parents=True, exist_ok=True)
    P = pd.read_csv(res / "p3" / "preds_disease.csv.gz", keep_default_na=False)
    prod = J["trust"]["disease_model"]
    # reliability diagrams (production disease model, before/after temperature)
    fig, axes = plt.subplots(1, 2, figsize=(9, 4))
    for ax, s in zip(axes, ("test", "wild"), strict=True):
        d = P[(P.config == prod) & (P.set == s)]
        for col, lab in (("p_raw", "before T"), ("p_cal", "after T")):
            conf = np.maximum(d[col], 1 - d[col])
            ok = ((d[col] >= 0.5).astype(int) == d.y)
            bins = np.linspace(0.5, 1, 6)
            idx = np.clip(np.digitize(conf, bins) - 1, 0, 4)
            xs = [conf[idx == i].mean() for i in range(5) if (idx == i).any()]
            ys = [ok[idx == i].mean() for i in range(5) if (idx == i).any()]
            ax.plot(xs, ys, "o-", label=lab)
        ax.plot([0.5, 1], [0.5, 1], "k:", lw=1)
        ax.set(title=f"{s} ({prod})", xlabel="confidence", ylabel="accuracy")
        ax.legend()
    fig.tight_layout()
    fig.savefig(fig_dir / names[0], dpi=110)
    plt.close(fig)
    # abstention curves
    fig, ax = plt.subplots(figsize=(5.5, 4))
    for s, lab in (("test", "TEST disease"), ("wild_all", "wild disease")):
        c = J["trust"]["sets"][s].get("disease", {}).get("abstention_curve")
        if c:
            ax.plot([x["coverage"] for x in c], [x["accuracy"] for x in c], "o-", ms=3, label=lab)
    for s, lab in (("test", "TEST crop"), ("wild_all", "wild crop")):
        c = J["trust"]["sets"][s]["crop"]["abstention_curve"]
        ax.plot([x["coverage"] for x in c], [x["accuracy"] for x in c], "--", label=lab)
    ax.set(xlabel="coverage (share answered)", ylabel="accuracy on answered", title="Abstention curves")
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(fig_dir / names[1], dpi=110)
    plt.close(fig)
    # confusion matrices
    fig, axes = plt.subplots(1, 2, figsize=(7, 3.4))
    for ax, s in zip(axes, ("test", "wild"), strict=True):
        d = P[(P.config == prod) & (P.set == s)]
        cm = np.zeros((2, 2), int)
        for y, p in zip(d.y, (d.p_cal >= 0.5).astype(int), strict=True):
            cm[y, p] += 1
        ax.imshow(cm, cmap="Greens")
        for i in range(2):
            for j in range(2):
                ax.text(j, i, cm[i, j], ha="center", va="center")
        ax.set(xticks=[0, 1], yticks=[0, 1], xticklabels=["healthy", "diseased"], yticklabels=["healthy", "diseased"],
               xlabel="predicted", ylabel="true", title=f"{s}: {prod}")
    fig.tight_layout()
    fig.savefig(fig_dir / names[2], dpi=110)
    plt.close(fig)
    # arms, wild macro-F1 with CI
    A = [(a, v) for a, v in J["disease_models"]["arms"].items() if "selected_config" in v]
    fig, ax = plt.subplots(figsize=(7, 4))
    for i, (_, v) in enumerate(A):
        for s, off, col in (("test", -0.15, "C0"), ("wild", 0.15, "C1")):
            m = v[s]["pooled"]
            lo, hi = m["ci95"]["macro_f1"]
            ax.errorbar(i + off, m["macro_f1"], yerr=[[m["macro_f1"] - lo], [hi - m["macro_f1"]]], fmt="o", color=col,
                        label=s if i == 0 else None)
    ax.set_xticks(range(len(A)), [a for a, _ in A], rotation=45, ha="right", fontsize=8)
    ax.set(ylabel="macro-F1 (95% CI)", title="Disease arms: TEST vs wild")
    ax.legend()
    fig.tight_layout()
    fig.savefig(fig_dir / names[3], dpi=110)
    plt.close(fig)
    return names


def fmt_ms(ms) -> str:
    return "n/a" if ms is None else f"{ms:.0f}"


