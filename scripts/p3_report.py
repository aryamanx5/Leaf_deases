         f"field_val`), holds {n['labelled']} disease-labelled leaves in {n['groups']} near-duplicate / scene / capture "
         f"groups (" + ", ".join(f"{k} {v}" for k, v in n["by_crop_label"].items()) + f") and {n['other']} leaves of "
