"""Run Stage 1 over every image in splits.csv -> data/processed/features.csv.

Parallel (joblib) with an on-disk JSON cache per image, keyed by the image path, file
size/mtime and a hash of the config sections that affect Stage 1. Feature names and
degenerate-case handling are written to results/feature_list.txt.
"""

from __future__ import annotations

import hashlib
import json
import sys
import time

import numpy as np
import pandas as pd
import yaml
from joblib import Parallel, delayed

from leafdx.config import ROOT, load_config, path
from leafdx.ip.features import FEATURE_NAMES, stage1
from leafdx.ip.preprocess import load_bgr

STAGE1_SECTIONS = ("preprocess", "segment", "lesions", "features", "seed")


def stage1_hash(cfg: dict) -> str:
    blob = yaml.safe_dump({k: cfg[k] for k in STAGE1_SECTIONS}, sort_keys=True)
    return hashlib.sha1(blob.encode()).hexdigest()[:12]


def one(p: str, crop: str, cfg: dict, cache_dir) -> dict:
    f = ROOT / p
    st = f.stat()
    key = hashlib.sha1(f"{p}|{st.st_size}|{st.st_mtime_ns}|{stage1_hash(cfg)}".encode()).hexdigest()
    cf = cache_dir / f"{key}.json"
    if cf.exists():
        return json.loads(cf.read_text())
    out = stage1(load_bgr(f), cfg, crop)
    rec = {"path": p, **out["features"], "seg_method": out["seg"]["method"],
           "seg_coverage": out["seg"]["coverage"], "stage1_ms": out["ms"]}
    cf.write_text(json.dumps(rec))
    return rec


def main() -> int:
    cfg = load_config()
    splits = pd.read_csv(path("splits", cfg))
    cache_dir = path("cache", cfg) / f"features_{stage1_hash(cfg)}"
    cache_dir.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    recs = Parallel(n_jobs=-1, verbose=0)(
        delayed(one)(r.path, r.crop, cfg, cache_dir) for r in splits.itertuples()
    )
    feats = pd.DataFrame(recs)
    df = splits.merge(feats, on="path", how="left", validate="one_to_one")
    out = path("features", cfg)
    df.to_csv(out, index=False)

    X = df[FEATURE_NAMES].to_numpy()
    n_bad = int((~np.isfinite(X)).sum())
    n_missing = int(df[FEATURE_NAMES].isna().any(axis=1).sum())
    lines = [
        f"# {len(FEATURE_NAMES)} Stage 1 features, in vector order (generated by scripts/extract_features.py)",
        "# Degenerate cases: segmentation failure -> whole frame used as leaf, seg_failed=1;",
        "#   no lesions -> lesion colour means = leaf means, lesion stds = 0, lesion shape features = 0;",
        "#   constant texture -> GLCM correlation = 0. All values finite (nan_to_num guard).",
        "# Hue: OpenCV 0-180 with red/purple (>=150) wrapped to negative; a*, b* centred at 0.",
        *FEATURE_NAMES,
    ]
    (path("results", cfg) / "feature_list.txt").write_text("\n".join(lines) + "\n")
    print(f"Wrote {out.relative_to(ROOT)}: {len(df)} rows x {len(FEATURE_NAMES)} features "
          f"in {time.time() - t0:.0f}s")
    print(f"non-finite values: {n_bad}; rows with missing features: {n_missing}; "
          f"seg_failed: {int(df.seg_failed.sum())}")
    print("seg method by stratum:")
    print(pd.crosstab(df.stratum, df.seg_method).to_string())
    print(f"stage1 ms/image (parallel workers, median): {df.stage1_ms.median():.0f}")
    return 0 if n_bad == 0 and n_missing == 0 and len(df) == len(splits) else 1


if __name__ == "__main__":
    sys.exit(main())
